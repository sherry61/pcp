-- 服务端角色、审计入口分配、节点查看凭据（演示用加密存储）

ALTER TABLE users
  ADD COLUMN role ENUM('USER','REGULATOR','AUDITOR','ADMIN') NOT NULL DEFAULT 'USER',
  ADD COLUMN trade_role ENUM('BUYER','SELLER','BOTH') NOT NULL DEFAULT 'BOTH',
  ADD COLUMN auditor_target VARCHAR(64) NULL;

CREATE TABLE IF NOT EXISTS pam_node_credentials (
  node_id VARCHAR(64) NOT NULL,
  node_name VARCHAR(128) NULL,
  username VARCHAR(128) NOT NULL,
  password_enc TEXT NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (node_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
